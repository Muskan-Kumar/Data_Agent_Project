from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="List of messages exchanged with the agent.")
    user_question: str = Field(..., description="The question asked by the user to the agent.")
    current_ques: str = Field(..., description="The current question being asked to the agent.")
    prompt_query_context: str = Field(..., description="The context of the prompt query for the agent.")
    is_safe: Literal["Yes", "No"] = Field(..., description="Indicates whether the agent's response is safe or not.")
    generated_sql_query: str = Field(..., description="The SQL query generated by the agent based on the prompt and context.")
    sql_query_excution_result: str = Field(..., description="The result of executing the generated SQL query.")
    final_answer: str = Field(..., description="The final answer provided by the agent after processing the prompt and context.")
    